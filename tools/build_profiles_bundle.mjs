/**
 * Compile tous les profils data/profiles/*.json (hors _*.json) dans :
 *   - data/account-profiles.js (window.TOG_PROFILES + window.TOG_DEFAULT_PROFILE_ID + window.TOG_ACCOUNT)
 *   - data/account-profile.js  (profil par défaut pour rétrocompatibilité)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, "..");

export function buildProfilesBundle(rootDir = ROOT_DIR) {
  const profilesDir = path.join(rootDir, "data", "profiles");
  fs.mkdirSync(profilesDir, { recursive: true });

  const files = fs.readdirSync(profilesDir)
    .filter(f => f.endsWith(".json") && !f.startsWith("_"))
    .sort((a, b) => a.localeCompare(b));

  const profiles = {};
  for (const file of files) {
    const idFallback = path.basename(file, ".json");
    const raw = JSON.parse(fs.readFileSync(path.join(profilesDir, file), "utf8"));
    const id = String(raw.profileId || idFallback).trim();
    raw.profileId = id;
    if (!raw.displayName) raw.displayName = id;
    profiles[id] = raw;
  }

  const keys = Object.keys(profiles);
  const defaultId = profiles.martin ? "martin" : (keys[0] || null);
  const defaultAcc = defaultId ? profiles[defaultId] : null;

  const bundleJs = `// Auto-generated by tools/build_profiles_bundle.mjs\n` +
    `(function (global) {\n` +
    `  "use strict";\n` +
    `  const PROFILES = ${JSON.stringify(profiles)};\n` +
    `  const DEFAULT_ID = ${JSON.stringify(defaultId)};\n` +
    `  const ACC = DEFAULT_ID ? PROFILES[DEFAULT_ID] : null;\n` +
    `  if (typeof module !== "undefined" && module.exports) {\n` +
    `    module.exports = { profiles: PROFILES, defaultProfileId: DEFAULT_ID, defaultAccount: ACC };\n` +
    `  }\n` +
    `  global.TOG_PROFILES = PROFILES;\n` +
    `  global.TOG_DEFAULT_PROFILE_ID = DEFAULT_ID;\n` +
    `  if (ACC) global.TOG_ACCOUNT = ACC;\n` +
    `})(typeof window !== "undefined" ? window : globalThis);\n`;

  const outBundlePath = path.join(rootDir, "data", "account-profiles.js");
  fs.writeFileSync(outBundlePath, bundleJs, "utf8");

  if (defaultAcc) {
    const singleJs = `// Auto-generated by tools/build_profiles_bundle.mjs\n` +
      `(function (global) {\n` +
      `  "use strict";\n` +
      `  const ACC = ${JSON.stringify(defaultAcc)};\n` +
      `  if (typeof module !== "undefined" && module.exports) module.exports = ACC;\n` +
      `  global.TOG_ACCOUNT = ACC;\n` +
      `})(typeof window !== "undefined" ? window : globalThis);\n`;
    fs.writeFileSync(path.join(rootDir, "data", "account-profile.js"), singleJs, "utf8");
  }

  return { outBundlePath, profileIds: keys, defaultId };
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(__filename)) {
  const res = buildProfilesBundle();
  console.log(`Built ${res.profileIds.length} profile(s): [${res.profileIds.join(", ")}] (default: ${res.defaultId}) -> ${res.outBundlePath}`);
}

